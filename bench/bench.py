"""Time one fixed generation of trials and record every trial's fitness.

This is "Step 0" of PERFORMANCE_OPTIONS.md: every speed change is measured with
this script, and its fitnesses are compared with a baseline (`bench/compare.py`)
to show whether the change kept the results the same.

The generation is fully determined by the arguments: the candidates are drawn
from a seeded generator (like a first CMA-ES generation: normal around 0 with
the config's CMA_INITIAL_STD, clipped to the bounds), and so are the ball poses.
Two runs with the same arguments therefore simulate exactly the same trials.

Settings that differ from the config (a shorter SIMULATION_TIME so a benchmark
finishes in minutes, the worker count, the physics options) are applied through
a small generated config that runs the real config and then overrides them. A
generated *file* is used, rather than changing attributes in this process,
because simulator workers on Windows and macOS start fresh and load the config
from its file: an override made only here would not reach them.

Usage (from the repository root):

    .venv/Scripts/python bench/bench.py --label baseline
    .venv/Scripts/python bench/bench.py --label implicitfast --set SIM_INTEGRATOR=implicitfast
    .venv/Scripts/python bench/compare.py bench/results/baseline.json bench/results/implicitfast.json
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import platform
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import paths  # noqa: E402

GENERATED_DIR = ROOT / "bench" / "_generated"
RESULTS_DIR = ROOT / "bench" / "results"


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """
    Parse the command line.

    :param argv: Arguments (defaults to sys.argv).
    :returns: Parsed arguments.
    """
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--config", default="config/spider_cmaes.py", help="config to benchmark")
    parser.add_argument("--label", required=True, help="name of this result (bench/results/<label>.json)")
    parser.add_argument("--candidates", type=int, default=24, help="controllers in the generation")
    parser.add_argument("--balls", type=int, default=2, help="training balls per controller")
    parser.add_argument("--sim-time", type=float, default=60.0, help="simulated seconds per trial")
    parser.add_argument("--workers", type=int, default=None, help="simulator processes (default: config)")
    parser.add_argument("--seed", type=int, default=12345, help="seed for candidates and balls")
    parser.add_argument(
        "--generations", type=int, default=1,
        help="evaluate the same generation this many times (results must repeat exactly)",
    )
    parser.add_argument(
        "--set",
        action="append",
        default=[],
        metavar="NAME=VALUE",
        help="override a config value (VALUE is a Python literal); repeatable",
    )
    parser.add_argument("--out", default=None, help="result path (default bench/results/<label>.json)")
    return parser.parse_args(argv)


def parse_overrides(pairs: list[str]) -> dict[str, object]:
    """
    Turn NAME=VALUE pairs into config overrides.

    VALUE is read as a Python literal (``0.002``, ``True``, ``"RK4"``); anything
    that is not a literal is kept as a string, so ``SIM_INTEGRATOR=implicitfast``
    works without quotes.

    :param pairs: The NAME=VALUE strings.
    :returns: Overrides by name.
    :raises SystemExit: If a pair has no '=' or the name is not an identifier.
    """
    import ast

    overrides: dict[str, object] = {}
    for pair in pairs:
        if "=" not in pair:
            raise SystemExit(f"--set expects NAME=VALUE, got {pair!r}")
        name, raw = pair.split("=", 1)
        name = name.strip()
        if not name.isidentifier():
            raise SystemExit(f"--set name {name!r} is not a valid identifier")
        try:
            overrides[name] = ast.literal_eval(raw)
        except (ValueError, SyntaxError):
            overrides[name] = raw
    return overrides


def write_generated_config(config_path: Path, label: str, overrides: dict[str, object]) -> Path:
    """
    Write a config that runs the real one and then applies the overrides.

    :param config_path: The real config.
    :param label: The benchmark label (names the generated file).
    :param overrides: Config values to replace.
    :returns: Path of the generated config.
    """
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    safe = "".join(c if c.isalnum() or c in "-_" else "_" for c in label)
    generated = GENERATED_DIR / f"{config_path.stem}__{safe}.py"
    lines = [
        '"""Generated by bench/bench.py: the real config, then benchmark overrides."""',
        f"_SOURCE = {str(config_path.resolve())!r}",
        "with open(_SOURCE, encoding='utf-8') as _handle:",
        "    exec(compile(_handle.read(), _SOURCE, 'exec'), globals())",
        "del _handle",
    ]
    for name, value in overrides.items():
        lines.append(f"{name} = {value!r}")
    generated.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return generated


def load_config(path: Path):
    """
    Load a config as the module named ``config``, the way training does.

    :param path: Config file.
    :returns: The config module.
    """
    spec = importlib.util.spec_from_file_location("config", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["config"] = module
    spec.loader.exec_module(module)
    return module


def make_candidates(num_params: int, count: int, seed: int, config) -> "list":
    """
    Draw a reproducible first generation.

    :param num_params: Controller parameter count.
    :param count: Number of candidates.
    :param seed: Generator seed.
    :param config: The config (for CMA_INITIAL_STD and CMA_BOUNDS, if present).
    :returns: Candidate parameter vectors.
    """
    import numpy as np

    rng = np.random.default_rng(seed)
    std = float(getattr(config, "CMA_INITIAL_STD", 0.3))
    low, high = getattr(config, "CMA_BOUNDS", [-1.0, 1.0])
    return [np.clip(rng.normal(0.0, std, num_params), low, high) for _ in range(count)]


def make_ball_poses(count: int, seed: int, config) -> list:
    """
    Draw reproducible training ball poses with the config's own factories.

    :param count: Number of poses.
    :param seed: Generator seed (offset from the candidate seed).
    :param config: The config.
    :returns: Ball poses.
    """
    import numpy as np

    rng = np.random.default_rng(seed + 1)
    set_factory = getattr(config, "make_training_ball_poses", None)
    if set_factory is not None:
        return list(set_factory(rng, count))
    factory = getattr(config, "make_training_ball_pose", config.make_random_ball_pose)
    return [factory(rng) for _ in range(count)]


def main(argv: list[str] | None = None) -> dict:
    """
    Run the benchmark and write its result.

    :param argv: Arguments (defaults to sys.argv).
    :returns: The result that was written.
    """
    args = parse_args(argv)
    config_path = (ROOT / args.config).resolve()
    overrides = {"SIMULATION_TIME": args.sim_time, **parse_overrides(args.set)}
    if args.workers is not None:
        overrides["NUM_SIMULATORS"] = args.workers
    generated = write_generated_config(config_path, args.label, overrides)

    paths.install(config_path.parent)
    sys.dont_write_bytecode = True
    config = load_config(generated)

    import logging

    logging.basicConfig(level=logging.WARNING)
    from evaluator import Evaluator

    evaluator = Evaluator()
    candidates = make_candidates(evaluator.num_parameters, args.candidates, args.seed, config)
    ball_poses = make_ball_poses(args.balls, args.seed, config)

    # Several generations of the same trials: the time includes what a real
    # run pays per generation (starting workers, unless they are kept), and
    # every repeat must give exactly the same answer.
    generation_seconds = []
    first = None
    for _ in range(max(1, args.generations)):
        start = time.perf_counter()
        means, trials, movements = evaluator.evaluate_on_ball_poses_full(candidates, ball_poses)
        generation_seconds.append(time.perf_counter() - start)
        if first is None:
            first = (means, trials, movements)
        elif json.dumps((means, trials, movements)) != json.dumps(first):
            raise SystemExit(f"{args.label}: a repeated generation gave a different result")
    evaluator.close()
    wall = sum(generation_seconds)

    import fast_trial

    num_trials = len(candidates) * len(ball_poses) * len(generation_seconds)
    result = {
        "label": args.label,
        "config": args.config,
        "overrides": {k: repr(v) for k, v in overrides.items()},
        "candidates": len(candidates),
        "balls": len(ball_poses),
        "trials": num_trials,
        "num_parameters": evaluator.num_parameters,
        "sim_time": args.sim_time,
        "workers": int(config.NUM_SIMULATORS),
        "seed": args.seed,
        "backend": getattr(config, "EVAL_BACKEND", "legacy"),
        "integrator": getattr(config, "SIM_INTEGRATOR", "RK4"),
        "timestep": getattr(config, "SIM_TIMESTEP", 0.001),
        "fast_trial": fast_trial.enabled(),
        "persistent_workers": evaluator._keep_pool(),
        "generations": len(generation_seconds),
        "generation_seconds": generation_seconds,
        "wall_seconds": wall,
        "seconds_per_trial": wall / num_trials,
        "trials_per_second": num_trials / wall,
        "mean_fitness": means,
        "trial_fitness": trials,
        "movements": movements,
        "machine": {
            "platform": platform.platform(),
            "processor": platform.processor(),
            "cpu_count": os.cpu_count(),
            "python": platform.python_version(),
        },
    }
    out = Path(args.out) if args.out else RESULTS_DIR / f"{args.label}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=1), encoding="utf-8")
    print(
        f"{args.label}: {num_trials} trials ({len(generation_seconds)} generation(s)) of "
        f"{args.sim_time:g} s on {result['workers']} worker(s) "
        f"in {wall:.1f} s  ({result['seconds_per_trial']:.2f} s/trial, "
        f"{result['trials_per_second']:.2f} trials/s)  -> {out}"
    )
    return result


if __name__ == "__main__":
    main()
